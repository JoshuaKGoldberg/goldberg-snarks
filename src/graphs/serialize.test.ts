import { describe, expect, it } from "vitest";

import { createGoldbergGraph } from "./createGoldbergGraph.ts";
import { toEdgeList, toGraph6 } from "./serialize.ts";

const vertices = Array.from({ length: 5 }, (_, i) => ({
	name: "abcde"[i],
	x: 0,
	y: 0,
}));

const edges = [
	{ from: 0, to: 2 },
	{ from: 4, to: 0 },
	{ from: 1, to: 3 },
	{ from: 3, to: 4 },
];

describe(toEdgeList, () => {
	it("lists one edge per line", () => {
		expect(toEdgeList({ edges, vertices })).toBe("a c\ne a\nb d\nd e\n");
	});
});

describe(toGraph6, () => {
	it("matches the example in the format's documentation", () => {
		expect(toGraph6({ edges, vertices })).toBe("DQc");
	});

	it("matches NetworkX when there are fewer than 63 vertices", () => {
		expect(toGraph6(createGoldbergGraph(3))).toBe(
			"WiGX?e??G?_A?AA@_H??H_G???G??G??GC?A??_W??c?O?H",
		);
	});

	it("matches NetworkX when there are more than 62 vertices", () => {
		expect(toGraph6(createGoldbergGraph(9))).toBe(
			"~?@GiGX?e??G?_A?AA@_H??H?G???G??G??G??A??_W??c???H??A?????_???G???A????G???_W???H?????c???A??????G?????_????A?????A????A@_????H??????H?????G???????G??????G??????G??????A??????_W??????c???????H??????A?????????_???????G???????A????????G???????_W???????H?????????c???????A??????????G?????????_????????A?????????A????????A@_????????H??????????H_????????G???????????G??????????G??????????GC?????????A??????????_W??????????c?O?????????H",
		);
	});
});
